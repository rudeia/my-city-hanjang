export function exampleFor(name: string, source = ""): WritingExample | undefined {
  if (!name.startsWith("plans.")) return fieldExamples[name];
  const [, index, key] = name.split(".");
  if (key === "learning" || key === "limit") return researchExamples[source]?.[key];
  const slot = ["action", "place", "reason"].indexOf(key);
  return slot < 0 ? undefined : strategyExamples[Number(index)]?.[slot];
}

